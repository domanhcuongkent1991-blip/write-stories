export type CliMessageKey = keyof typeof CLI_MESSAGES;
export type CliFormatValues = Readonly<Record<string, string | number | boolean>>;

const PLACEHOLDER_PATTERN = /\{([A-Za-z][A-Za-z0-9]*)\}/g;

export function formatCliMessage(
  locale: CliLocale,
  key: CliMessageKey,
  values: CliFormatValues = {},
): string {
  const base = CLI_MESSAGES[key];
  const viMessages: Partial<Record<CliMessageKey, string>> = VI_MESSAGES;
  const template = locale === "vi"
    ? viMessages[key] ?? base.en
    : locale === "en" ? base.en : base.zh;

  return template.replace(PLACEHOLDER_PATTERN, (token: string, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token
  ));
}

export function formatCurrentCliMessage(
  key: CliMessageKey,
  values?: CliFormatValues,
): string {
  return formatCliMessage(resolveCliLocale(), key, values);
}
