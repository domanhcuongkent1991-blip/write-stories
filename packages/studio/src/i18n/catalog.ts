export function getPlaceholderNames(template: string): readonly string[] {
  const names = [...template.matchAll(/\{([A-Za-z0-9_]+)\}/g)]
    .map((match) => match[1])
    .filter((name): name is string => name !== undefined);
  return [...new Set(names)].sort();
}

